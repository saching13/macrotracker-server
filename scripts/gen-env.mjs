#!/usr/bin/env node
// Writes a fresh .env with random secrets and a GoTrue signing keypair.
// Usage: node scripts/gen-env.mjs [out-file]   (refuses to overwrite)
import { existsSync, writeFileSync } from 'node:fs';
import { randomBytes, randomUUID, webcrypto } from 'node:crypto';

const out = process.argv[2] ?? '.env';
if (existsSync(out)) {
  console.error(`${out} already exists; delete it first if you really want new secrets.`);
  process.exit(1);
}

const secret = (bytes = 32) => randomBytes(bytes).toString('base64url');

const { privateKey } = await webcrypto.subtle.generateKey({ name: 'ECDSA', namedCurve: 'P-256' }, true, [
  'sign',
  'verify',
]);
const ec = await webcrypto.subtle.exportKey('jwk', privateKey);
const jwtSecret = secret(48);

// GoTrue signs user tokens with the EC key (published at /.well-known/jwks.json)
// and accepts the HS256 key only for verifying the API's service-role tokens.
const jwtKeys = [
  {
    kty: 'EC',
    crv: ec.crv,
    x: ec.x,
    y: ec.y,
    d: ec.d,
    kid: randomUUID(),
    alg: 'ES256',
    use: 'sig',
    key_ops: ['sign', 'verify'],
  },
  {
    kty: 'oct',
    k: Buffer.from(jwtSecret).toString('base64url'),
    kid: randomUUID(),
    alg: 'HS256',
    key_ops: ['verify'],
  },
];

const env = `# Generated by scripts/gen-env.mjs on ${new Date().toISOString()}. Keep this file secret.
POSTGRES_PASSWORD=${secret()}
MT_OWNER_PASSWORD=${secret()}
MT_API_PASSWORD=${secret()}
JWT_SECRET=${jwtSecret}
JWT_KEYS='${JSON.stringify(jwtKeys)}'
# Address people open the server at (tailnet or public). Invite/reset links use it.
PUBLIC_URL=http://localhost:8080
# Comma-separated browser origins allowed to call the API with credentials.
WEB_ORIGINS=http://localhost:5173
LOG_LEVEL=info
# AI agents (MCP at /mcp): on; logging and editing allowed; deleting off.
MCP_ENABLED=true
MCP_WRITE_ENABLED=true
MCP_DESTROY_ENABLED=false
# "Today" for agents that don't name a day.
DEFAULT_TIMEZONE=UTC
`;
writeFileSync(out, env, { mode: 0o600 });
console.log(`Wrote ${out}`);
